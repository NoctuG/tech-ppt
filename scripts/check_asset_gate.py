#!/usr/bin/env python3
"""Check preassembly asset coverage and files; does not attest generation or visual QA."""
import argparse
import hashlib
import json
from pathlib import Path
import sys


def inspect(manifest, base):
    issues, warnings = [], []
    version = manifest.get('style_version')
    if not isinstance(version, str) or not version.strip():
        issues.append('Missing style_version.')

    def file_check(value, label, image=False, expected_hash=None):
        if not isinstance(value, str) or not value.strip():
            issues.append(label + ': missing file.')
            return None
        path = base / value
        try:
            data = path.read_bytes()
        except OSError as error:
            issues.append(label + ': unreadable file: ' + str(error))
            return None
        if not data:
            issues.append(label + ': empty file.')
            return None
        if image and not (
            data.startswith(b'\x89PNG\r\n\x1a\n') or data.startswith(b'\xff\xd8\xff')
            or data.startswith((b'GIF87a', b'GIF89a'))
            or (data.startswith(b'RIFF') and data[8:12] == b'WEBP')
        ):
            issues.append(label + ': unsupported or missing raster image signature.')
        digest = hashlib.sha256(data).hexdigest()
        if expected_hash and digest.lower() != str(expected_hash).lower():
            issues.append(label + ': SHA-256 differs from manifest.')
        return digest

    file_check(manifest.get('style_spec'), 'style_spec')
    anchors = manifest.get('anchors', [])
    if not isinstance(anchors, list):
        issues.append('anchors must be a list.')
        anchors = []
    for role in ('cover', 'inner'):
        selected = [a for a in anchors if isinstance(a, dict) and a.get('role') == role]
        if len(selected) != 1:
            issues.append('Exactly one reviewed anchor required for ' + role + '.')
            continue
        anchor = selected[0]
        if anchor.get('reviewed') is not True:
            issues.append(role + ': anchor not reviewed.')
        file_check(anchor.get('file'), role + ' anchor', image=True)

    entries = manifest.get('assets', [])
    if not isinstance(entries, list):
        issues.append('assets must be a list.')
        entries = []
    assets, generated_hashes = {}, {}
    sources = {'generated', 'textbook', 'provided', 'native'}
    for asset in entries:
        if not isinstance(asset, dict) or not isinstance(asset.get('id'), str) or not asset['id'].strip():
            issues.append('Asset must have a nonempty string id.')
            continue
        ident = asset['id']
        if ident in assets:
            issues.append('Duplicate asset id: ' + ident)
        assets[ident] = asset
        source = asset.get('source')
        if source not in sources:
            issues.append(ident + ': invalid source.')
        if asset.get('accepted') is not True:
            issues.append(ident + ': not accepted.')
        if source != 'native':
            digest = file_check(asset.get('file'), ident, image=True, expected_hash=asset.get('sha256'))
        else:
            digest = None
            if not asset.get('role'):
                issues.append(ident + ': native asset missing role.')
        if source == 'generated':
            if asset.get('style_version') != version:
                issues.append(ident + ': stale or missing style_version.')
            for field in ('tool', 'generation_id'):
                if not isinstance(asset.get(field), str) or not asset[field].strip():
                    issues.append(ident + ': missing generation record ' + field + '.')
            file_check(asset.get('prompt_file'), ident + ' prompt')
            if digest and digest in generated_hashes:
                issues.append(ident + ': duplicate generated bytes; reuse asset id ' + generated_hashes[digest] + '.')
            elif digest:
                generated_hashes[digest] = ident

    required = manifest.get('required_generated_ids')
    if not isinstance(required, list) or any(not isinstance(i, str) for i in required):
        issues.append('required_generated_ids must be a list of strings.')
        required = []
    if len(required) != len(set(required)):
        issues.append('Duplicate required_generated_ids.')
    authorization = manifest.get('existing_only_authorization')
    if not required and not (isinstance(authorization, str) and authorization.strip()):
        issues.append('No required generation; record explicit existing-only authorization or retain required generation.')
    for ident in required:
        if ident not in assets or assets[ident].get('source') != 'generated':
            issues.append('Required generation missing or reassigned: ' + ident)

    pages = manifest.get('pages', [])
    if not isinstance(pages, list) or not pages:
        issues.append('pages must be a nonempty list.')
        pages = []
    used, page_ids, slot_count, mapped = set(), set(), 0, 0
    for page in pages:
        if not isinstance(page, dict) or not isinstance(page.get('id'), str):
            issues.append('Page missing string id.')
            continue
        ident = page['id']
        if ident in page_ids:
            issues.append('Duplicate page id: ' + ident)
        page_ids.add(ident)
        slots = page.get('visual_slots')
        if not isinstance(slots, list):
            issues.append(ident + ': visual_slots must be a list.')
            continue
        if not slots and not page.get('visual_reason'):
            issues.append(ident + ': empty visual_slots require visual_reason.')
        for slot in slots:
            slot_count += 1
            asset_id = slot.get('asset_id') if isinstance(slot, dict) else None
            if not isinstance(slot, dict) or not slot.get('role'):
                issues.append(ident + ': visual slot missing role.')
            if not isinstance(asset_id, str) or asset_id not in assets:
                issues.append(ident + ': unresolved asset ' + str(asset_id))
            else:
                mapped += 1
                used.add(asset_id)
    for ident in required:
        if ident not in used:
            issues.append('Required generated asset unused: ' + ident)
    unused = sorted(set(assets) - used)
    if unused:
        warnings.append('Unused active assets: ' + ', '.join(unused))
    return {
        'passed': not issues, 'issues': issues, 'warnings': warnings,
        'pages': len(pages), 'necessary_slots': slot_count, 'mapped_slots': mapped,
        'slot_mapping_ratio': mapped / slot_count if slot_count else None,
        'required_generated_items': len(required),
        'generated_files_with_unique_bytes': len(generated_hashes),
        'limits': 'Files, signatures, recorded status and references only. Does not prove model calls, image decoding, visual quality, teaching accuracy or slideshow behavior.'
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifest', type=Path)
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    try:
        manifest = json.loads(args.manifest.read_text(encoding='utf-8-sig'))
        if not isinstance(manifest, dict):
            raise ValueError('Manifest must be an object.')
        report = inspect(manifest, args.manifest.resolve().parent)
    except (OSError, ValueError, TypeError) as error:
        print('Asset gate failed: ' + str(error), file=sys.stderr)
        return 2
    output = json.dumps(report, ensure_ascii=False, indent=2)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(output, encoding='utf-8')
    print(output)
    return 0 if report['passed'] else 1


if __name__ == '__main__':
    sys.exit(main())
